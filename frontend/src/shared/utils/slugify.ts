// Suggests a URL slug from a board name. Used by the create wizard: user types
// "Культурная карта" in Russian, we propose "kulturnaya-karta" in the slug field.
// The user can rewrite it; the backend validates and does the final uniqueness check.

const CYRILLIC_MAP: Record<string, string> = {
  а: 'a', б: 'b', в: 'v', г: 'g', д: 'd', е: 'e', ё: 'yo', ж: 'zh',
  з: 'z', и: 'i', й: 'y', к: 'k', л: 'l', м: 'm', н: 'n', о: 'o',
  п: 'p', р: 'r', с: 's', т: 't', у: 'u', ф: 'f', х: 'h', ц: 'ts',
  ч: 'ch', ш: 'sh', щ: 'shch', ъ: '', ы: 'y', ь: '', э: 'e', ю: 'yu', я: 'ya',
}

export function slugify(input: string): string {
  const lowered = input.toLowerCase()
  let out = ''
  for (const ch of lowered) {
    out += CYRILLIC_MAP[ch] ?? ch
  }
  return out
    .replace(/[^a-z0-9-]+/g, '-')
    .replace(/-+/g, '-')
    .replace(/^-|-$/g, '')
    .slice(0, 64)
}
